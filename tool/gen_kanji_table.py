#!/usr/bin/env python3
"""Generates lib/src/encoder/kanji_table.dart.

QR Kanji mode (ISO/IEC 18004:2015, 7.4.6) encodes Shift JIS double-byte
characters in the ranges 0x8140-0x9FFC and 0xE040-0xEBBF as 13-bit values.

The mapping from Shift JIS to Unicode comes from CPython's `shift_jis` codec
(JIS X 0208). A character is kept only when CPython's `cp932` codec decodes the
same bytes to the same code point, so characters whose Unicode mapping differs
between Shift JIS variants (for example WAVE DASH versus FULLWIDTH TILDE) are
left to byte mode. Code points below U+0100 are also excluded so that Latin-1
text never switches to Kanji mode.

Run from the package root: python3 tool/gen_kanji_table.py
"""

def entry(value):
    hi, lo = divmod(value, 0xC0)
    code = (hi << 8) | lo
    code += 0x8140 if code <= 0x9FFC - 0x8140 else 0xC140
    if not (0x8140 <= code <= 0x9FFC or 0xE040 <= code <= 0xEBBF):
        return None
    raw = bytes([code >> 8, code & 0xFF])
    try:
        a = raw.decode('shift_jis')
        b = raw.decode('cp932')
    except UnicodeDecodeError:
        return None
    if a != b or len(a) != 1 or ord(a) < 0x100 or ord(a) > 0xFFFF:
        return None
    return a


def main():
    chars = []
    count = 0
    for v in range(8192):
        c = entry(v)
        if c is None:
            chars.append('\\x00')
        else:
            count += 1
            chars.append(c)
    lines = [''.join(chars[i:i + 32]) for i in range(0, len(chars), 32)]
    with open('lib/src/encoder/kanji_table.dart', 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tool/gen_kanji_table.py. Do not edit by hand.\n')
        f.write('// Source: CPython shift_jis codec (JIS X 0208), cross-checked with cp932.\n')
        f.write(f'// {count} characters.\n\n')
        f.write('/// Character at each 13-bit QR Kanji value, or U+0000 when unused.\n')
        f.write('const String kanjiTable =\n')
        for i, line in enumerate(lines):
            end = ';' if i == len(lines) - 1 else ''
            f.write(f"    '{line}'{end}\n")
    print(count)


if __name__ == '__main__':
    main()
